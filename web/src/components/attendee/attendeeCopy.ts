export type CopyLocale = "fa" | "en";

/** Digits in the reader's script ("12" / "۱۲"). */
export const n = (value: number, locale: CopyLocale) => new Intl.NumberFormat(locale === "fa" ? "fa-IR" : "en-US").format(value);

/** A count as words: zero is a sentence ("No contacts yet"), never a bare «۰». */
export function contactsPhrase(count: number, locale: CopyLocale): string {
  if (locale === "fa") return count === 0 ? "هنوز مخاطبی ندارید" : `${n(count, locale)} مخاطب`;
  if (count === 0) return "No contacts yet";
  return `${n(count, locale)} contact${count === 1 ? "" : "s"}`;
}

